// Recursively convert all leaf values to string
type DeepStringify<T> = {
    [K in keyof T]: T[K] extends readonly (infer _U)[]
        ? string[]
        : T[K] extends Record<string, unknown>
          ? DeepStringify<T[K]>
          : string;
};

export type TranslationSchema = DeepStringify<typeof en>;
